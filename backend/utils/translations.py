def get_translation(key: str, lang: str | None = None) -> str:
    """
    Return the English translation for *key*.

    The *lang* parameter is accepted for backwards compatibility but ignored —
    the system operates exclusively in English.

    Falls back to the key itself when translation is missing, so untranslated
    keys are always visible and easy to spot during development.

    Args:
        key:  Translation key (e.g. 'dashboard').
        lang: Ignored. Always returns English translation.
    """
    return _translations["en"].get(key, key)
